def render(word, max_width=80):
    word = word.upper()
    missing = sorted({c for c in word if c not in FONT})
    if missing:
        sys.exit(f"no glyph for: {''.join(missing)}")
    need = len(word) * 6 + max(0, len(word) - 1)
    if need > max_width:
        sys.exit(f"'{word}' needs {need} columns, budget is {max_width}")

    rows = [FONT[c].split("|") for c in word]
    out = []
    for pair in ((0, 1), (2, 3), (4, 5), (6, 7)):
        line = []
        for glyph in rows:
            for col in range(6):
                top = glyph[pair[0]][col] == "#"
                bot = glyph[pair[1]][col] == "#"
                line.append("\u2588" if top and bot else "\u2580" if top
                            else "\u2584" if bot else " ")
            line.append(" ")
        out.append("".join(line).rstrip())
    return "\n".join(out) + "\n"

if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    width = int(sys.argv[sys.argv.index("--width") + 1]) if "--width" in sys.argv else 80
    if not args:
        sys.exit(__doc__)
    sys.stdout.write(render(" ".join(args), width))
